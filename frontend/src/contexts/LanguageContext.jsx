const getInitialLanguage = () => {
  try {
    const savedLanguage = localStorage.getItem(LANGUAGE_KEY);
    if (SUPPORTED_LANGUAGES.includes(savedLanguage)) return savedLanguage;
  } catch {
    // Keep the default language when browser storage is unavailable.
  }
  return "fr";
};

const translateText = (text, language) => {
  if (language === "fr") return text;
  const leadingSpace = text.match(/^\s*/)?.[0] ?? "";
  const trailingSpace = text.match(/\s*$/)?.[0] ?? "";
  const phrase = text.trim();
  const translated = translations[language][phrase];
  if (!translated) return text;
  return `${leadingSpace}${translated}${trailingSpace}`;
};

const translateTree = (node, language) => {
  if (typeof node === "string") return translateText(node, language);
  if (!isValidElement(node)) return node;
  if (node.props["data-no-translate"]) return node;

  const translatedProps = {};
  for (const attribute of ["aria-label", "placeholder", "title"]) {
    const value = node.props[attribute];
    if (typeof value === "string") {
      translatedProps[attribute] = translateText(value, language);
    }
  }
  if (node.type === "option" && node.props.value === undefined) {
    const optionValue = Children.toArray(node.props.children)
      .map((child) =>
        typeof child === "string" || typeof child === "number" ? child : "",
      )
      .join("");
    translatedProps.value = optionValue;
  }
  const children = Children.map(node.props.children, (child) =>
    translateTree(child, language),
  );
  if (isValidElement(node.props.fallback)) {
    translatedProps.fallback = translateTree(node.props.fallback, language);
  }
  return cloneElement(node, translatedProps, children);
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      localStorage.setItem(LANGUAGE_KEY, language);
    } catch {
      // The selected language remains active for the current session.
    }
  }, [language]);

  const contextValue = useMemo(() => ({ language, setLanguage }), [language]);
  return (
    <LanguageContext.Provider value={contextValue}>
      {children}
    </LanguageContext.Provider>
  );
};

// eslint-disable-next-line react-refresh/only-export-components
export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage doit être utilisé dans <LanguageProvider>");
  }
  return context;
};

export const Localized = ({ children }) => {
  const { language } = useLanguage();
  return translateTree(children, language);
};
